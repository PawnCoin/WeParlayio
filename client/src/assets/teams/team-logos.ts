// Function to get team logo path
export const getTeamLogoPath = (teamName: string, league: string = 'nba'): string => {
  const leagueLogos = teamLogoPaths[league.toLowerCase() as keyof typeof teamLogoPaths];
  if (leagueLogos && leagueLogos[teamName as keyof typeof leagueLogos]) {
    return leagueLogos[teamName as keyof typeof leagueLogos];
  }
  // Fallback to existing team logos in teamLogos.ts if not found
  return `/src/assets/teams/${league.toLowerCase()}/${teamName.toLowerCase().replace(/\s+/g, '-')}.svg`;
};
