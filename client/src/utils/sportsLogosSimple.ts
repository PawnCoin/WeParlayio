// Helper functions
export const getTeamLogo = (teamName: string, sport: string = ''): string => {
  const normalizedTeam = teamName.toLowerCase();
  
  // Check sport-specific team logos
  if (sport.toLowerCase().includes('nfl') || sport.toLowerCase().includes('football')) {
    return NFL_TEAM_LOGOS[normalizedTeam] || '';
  }
  
  if (sport.toLowerCase().includes('nba') || sport.toLowerCase().includes('basketball')) {
    return NBA_TEAM_LOGOS[normalizedTeam] || '';
  }
  
  if (sport.toLowerCase().includes('mlb') || sport.toLowerCase().includes('baseball')) {
    return MLB_TEAM_LOGOS[normalizedTeam] || '';
  }
  
  if (sport.toLowerCase().includes('nhl') || sport.toLowerCase().includes('hockey')) {
    return NHL_TEAM_LOGOS[normalizedTeam] || '';
  }
  
  // Check all team logos if sport not specified
  return NFL_TEAM_LOGOS[normalizedTeam] || 
         NBA_TEAM_LOGOS[normalizedTeam] || 
         MLB_TEAM_LOGOS[normalizedTeam] || 
         NHL_TEAM_LOGOS[normalizedTeam] || 
         '';
};

export const getLeagueLogo = (league: string): string => {
  return LEAGUE_LOGOS[league] || SPORTS_LOGOS[league.toLowerCase()] || '';
};

export const getEsportsLogo = (game: string): string => {
  return ESPORTS_LOGOS[game.toLowerCase() as keyof typeof ESPORTS_LOGOS] || '';
};

// Get team initials for fallback display
export const getTeamInitials = (teamName: string): string => {
  return teamName
    .split(' ')
    .map(word => word[0])
    .join('')
    .toUpperCase()
    .slice(0, 2);
};